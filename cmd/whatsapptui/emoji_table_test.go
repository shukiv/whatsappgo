package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
	"testing"
)

var updateEmoji = flag.Bool("update-emoji", false, "rewrite emoji_table.go from the desktop client's EmojiPicker.qml")

// The desktop client's emoji groups, as EmojiPicker.qml writes them: a group
// begins with its name and icon and lists its items, a few to a line, until
// a line that closes the list.
var (
	qmlEmojiGroup = regexp.MustCompile(`name: qsTr\("([^"]+)"\), icon: "([^"]+)", items: \[`)
	qmlEmojiItem  = regexp.MustCompile(`"([^"\\]*)"`)
)

const emojiTableHeader = `// Code generated by go generate from desktop/qml/EmojiPicker.qml; DO NOT EDIT.
// The terminal offers the desktop client's emoji, group for group, so the
// two windows show the same choice. Each item is the emoji and the words it
// is found by, as the desktop client keeps them.

package main

`

// emojiTableSource is emoji_table.go as the desktop client's list makes it,
// line for line with the list.
func emojiTableSource(qml []byte) ([]byte, error) {
	var out bytes.Buffer
	out.WriteString(emojiTableHeader)
	out.WriteString("var emojiGroups = []emojiGroup{\n")
	groups, inGroup := 0, false
	for _, line := range strings.Split(string(qml), "\n") {
		if found := qmlEmojiGroup.FindStringSubmatch(line); found != nil {
			fmt.Fprintf(&out, "\t{name: %s, icon: %s, items: []string{\n", strconv.Quote(found[1]), strconv.Quote(found[2]))
			groups, inGroup = groups+1, true
			continue
		}
		if !inGroup {
			continue
		}
		if strings.TrimSpace(line) == "]" {
			out.WriteString("\t}},\n")
			inGroup = false
			continue
		}
		var items []string
		for _, found := range qmlEmojiItem.FindAllStringSubmatch(line, -1) {
			items = append(items, strconv.Quote(found[1]))
		}
		if len(items) > 0 {
			fmt.Fprintf(&out, "\t\t%s,\n", strings.Join(items, ", "))
		}
	}
	if groups == 0 || inGroup {
		return nil, fmt.Errorf("EmojiPicker.qml no longer lists its groups the way this reads them (%d groups found)", groups)
	}
	out.WriteString("}\n")
	return format.Source(out.Bytes())
}

// The terminal's emoji are the desktop client's. Changing the desktop's list
// fails this test until `go generate ./cmd/whatsapptui` writes the terminal's
// again, which it does by running this test with -update-emoji.
func TestTheEmojiAreTheDesktopClients(t *testing.T) {
	qml, err := os.ReadFile(filepath.Join("..", "..", "desktop", "qml", "EmojiPicker.qml"))
	if err != nil {
		t.Fatal(err)
	}
	want, err := emojiTableSource(qml)
	if err != nil {
		t.Fatal(err)
	}
	if *updateEmoji {
		if err := os.WriteFile("emoji_table.go", want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile("emoji_table.go")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Fatal("emoji_table.go is not what the desktop client's EmojiPicker.qml makes; run go generate ./cmd/whatsapptui")
	}
}
